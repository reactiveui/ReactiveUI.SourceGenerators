using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using ReactiveUI.SourceGenerators.CodeGeneration;
using ReactiveUI.SourceGenerators.Extensions;
using ReactiveUI.SourceGenerators.Helpers;
using ReactiveUI.SourceGenerators.Models;

namespace ReactiveUI.SourceGenerators;

/// <summary>A source generator for generating reactive properties.</summary>
[Generator(LanguageNames.CSharp)]
public sealed class ReactiveObjectGenerator : IIncrementalGenerator
{
    /// <summary>Gets the generator type name used in generated-code metadata.</summary>
    internal static readonly string GeneratorName = typeof(ReactiveObjectGenerator).FullName!;

    /// <summary>Gets the generator assembly version used in generated-code metadata.</summary>
    internal static readonly string GeneratorVersion = typeof(ReactiveObjectGenerator).Assembly.GetName().Version.ToString();

    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        // Gather info for all annotated IReactiveObject Classes, one output per type.
        var types =
            context.SyntaxProvider
            .ForAttributeWithMetadataName(
                AttributeDefinitions.ReactiveObjectAttributeType,
                static (node, _) => node is ClassDeclarationSyntax { AttributeLists.Count: > 0 } declaration && declaration.Modifiers.Any(SyntaxKind.PartialKeyword),
                static (context, token) => GetClassInfo(context, token))
            .Where(static x => x is not null)
            .Select(static (x, _) => x!)
            .GroupByTarget(static info => info.TargetInfo)
            .WithTrackingName(TrackingNames.ReactiveObjectTypes);

        context.RegisterSourceOutput(types.Combine(context.ReactiveUiIntegration()), static (context, input) =>
        {
            var target = input.Left[0].TargetInfo;
            context.AddSource($"{target.FileHintName}.IReactiveObject.g.cs", GenerateSource(target, input.Right));
        });
    }

    /// <summary>Creates metadata for a ReactiveObject-annotated class.</summary>
    /// <param name="context">The attribute syntax context for the class.</param>
    /// <param name="token">The cancellation token for the generator operation.</param>
    /// <returns>The class metadata, or <see langword="null"/> when not applicable.</returns>
    private static ReactiveObjectInfo? GetClassInfo(in GeneratorAttributeSyntaxContext context, CancellationToken token)
    {
        if (!(context.TargetNode is ClassDeclarationSyntax declaredClass && declaredClass.Modifiers.Any(SyntaxKind.PartialKeyword)))
        {
            return default;
        }

        var symbol = context.TargetSymbol;
        token.ThrowIfCancellationRequested();

        if (symbol is not INamedTypeSymbol classSymbol)
        {
            return default;
        }

        token.ThrowIfCancellationRequested();

        // Get the containing type info
        var targetInfo = TargetInfo.From(classSymbol);

        token.ThrowIfCancellationRequested();
        return new(targetInfo);
    }

    /// <summary>Generates the complete source document for a ReactiveObject declaration.</summary>
    /// <param name="target">The type that implements <c>IReactiveObject</c>.</param>
    /// <param name="integration">The selected ReactiveUI integration metadata.</param>
    /// <returns>The generated source document.</returns>
    private static string GenerateSource(TargetInfo target, ReactiveUiIntegration integration)
    {
        var writer = SourceWriter.Rent()
            .AutoGenerated()
            .DisableWarningsEnableNullable()
            .Using("System")
            .Using("System.Diagnostics.CodeAnalysis")
            .Using("System.ComponentModel")
            .Lines(integration.UsingDirectives)
            .BlankLine();

        // Only the namespace encloses the type: containing types have never been declared around it.
        var depth = writer.OpenNamespace(target.TargetNamespace);
        _ = writer.Line("/// <summary>")
            .Append("/// Partial class for the ").Append(target.TargetName).Line(" which contains ReactiveUI IReactiveObject initialization.")
            .Line("/// </summary>")
            .OpenPartialType(target, "IReactiveObject")
            .Lines(ReactiveObjectSource.Members);

        return writer.CloseBlock()
            .CloseBlocks(depth)
            .RestoreNullableAndWarnings()
            .ToStringAndReturn();
    }

    /// <summary>Contains reusable generated ReactiveObject source fragments.</summary>
    private static class ReactiveObjectSource
    {
        /// <summary>Contains the generated ReactiveObject event implementation.</summary>
        internal const string Members = """
        private bool _propertyChangingEventsSubscribed;
        private bool _propertyChangedEventsSubscribed;

        /// <inheritdoc/>
        public event PropertyChangingEventHandler? PropertyChanging
        {
            add
            {
                if (!_propertyChangingEventsSubscribed)
                {
                    this.SubscribePropertyChangingEvents();
                    _propertyChangingEventsSubscribed = true;
                }

                PropertyChangingHandler += value;
            }
            remove => PropertyChangingHandler -= value;
        }

        /// <inheritdoc/>
        public event PropertyChangedEventHandler? PropertyChanged
        {
            add
            {
                if (!_propertyChangedEventsSubscribed)
                {
                    this.SubscribePropertyChangedEvents();
                    _propertyChangedEventsSubscribed = true;
                }

                PropertyChangedHandler += value;
            }
            remove => PropertyChangedHandler -= value;
        }

        [SuppressMessage("Roslynator", "RCS1159:Use EventHandler<T>", Justification = "Long term design.")]
        private event PropertyChangingEventHandler? PropertyChangingHandler;

        [SuppressMessage("Roslynator", "RCS1159:Use EventHandler<T>", Justification = "Long term design.")]
        private event PropertyChangedEventHandler? PropertyChangedHandler;

        /// <inheritdoc/>
        void IReactiveObject.RaisePropertyChanging(PropertyChangingEventArgs args) =>
            PropertyChangingHandler?.Invoke(this, args);

        /// <inheritdoc/>
        void IReactiveObject.RaisePropertyChanged(PropertyChangedEventArgs args) =>
            PropertyChangedHandler?.Invoke(this, args);
        """;
    }
}
